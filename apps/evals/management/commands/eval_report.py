"""Write docs/RESULTS.md from a recorded eval run.

The report is generated, never hand-written, so a number cannot drift from the run
that produced it. The mode banner is deliberately blunt: an oracle run measures the
harness, and quoting its accuracy as model quality would be a lie.
"""
from __future__ import annotations

from collections import defaultdict
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

from apps.evals.models import EvalRun

REPO_ROOT = Path(settings.BASE_DIR)
DEFAULT_OUTPUT = REPO_ROOT / "docs" / "RESULTS.md"

BANNERS = {
    EvalRun.Mode.ORACLE: (
        "**Mode: ORACLE — harness self-check.**\n\n"
        "The model's decisions in this run were scripted from the dataset's expected\n"
        "behaviour. These numbers verify that the **harness** computes correctly\n"
        "(metrics, gates, report). They are **not** a measurement of any model and must\n"
        "not be quoted as accuracy. To measure a model, record cassettes and run\n"
        "`--mode replay`, or run `--mode live`."
    ),
    EvalRun.Mode.REPLAY: (
        "**Mode: REPLAY — recorded model decisions.**\n\n"
        "Model responses were replayed from cassettes, so this run is deterministic and\n"
        "free. It measures the recorded model's decisions against the golden set."
    ),
    EvalRun.Mode.LIVE: (
        "**Mode: LIVE — a real model was called.**\n\n"
        "This run measures model quality directly. It costs money and is not\n"
        "deterministic; record cassettes from it so CI can replay it for free."
    ),
}


def _fmt(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def _pct(value) -> str:
    if value is None:
        return "—"
    return f"{value * 100:.1f}%"


class Command(BaseCommand):
    help = "Generate docs/RESULTS.md from an eval run."

    def add_arguments(self, parser):
        parser.add_argument("--run-id", type=int, default=None, help="Defaults to the latest run.")
        parser.add_argument("--output", default=str(DEFAULT_OUTPUT))

    def handle(self, *args, **options):
        if options["run_id"]:
            run = EvalRun.objects.filter(pk=options["run_id"]).first()
            if run is None:
                raise CommandError(f"No EvalRun with id {options['run_id']}.")
        else:
            run = EvalRun.objects.order_by("-created_at").first()
            if run is None:
                raise CommandError("No eval runs yet. Run `manage.py run_evals` first.")

        metrics = run.metrics or {}
        results = list(run.results.all())

        by_kind: dict[str, list] = defaultdict(list)
        for result in results:
            by_kind[result.kind or "unknown"].append(result)

        lines: list[str] = []
        lines.append("# DeskPilot — evaluation results")
        lines.append("")
        lines.append(
            f"> Generated from **EvalRun #{run.pk}** by `make report`. "
            "Do not edit this file by hand."
        )
        lines.append("")
        lines.append(BANNERS.get(run.mode, ""))
        lines.append("")
        lines.append("---")
        lines.append("")
        lines.append("## Run")
        lines.append("")
        lines.append("| | |")
        lines.append("|---|---|")
        lines.append(f"| Mode | `{run.mode}` |")
        lines.append(f"| Model | `{run.model or 'n/a'}` |")
        lines.append(f"| Prompt version | `{run.prompt_version or 'n/a'}` |")
        lines.append(f"| Cases | {run.case_count} |")
        lines.append(f"| Disposition matches | {run.passed_count} |")
        lines.append(f"| Gates passed | {'yes' if run.gates_passed else 'no'} |")
        lines.append(f"| Run duration | {run.duration_ms / 1000:.1f}s |")
        if run.notes:
            lines.append(f"| Notes | {run.notes.strip()} |")
        lines.append("")

        lines.append("## Headline metrics")
        lines.append("")
        lines.append("| Metric | Value |")
        lines.append("|---|---|")
        lines.append(f"| Triage (category) accuracy | {_pct(metrics.get('triage_accuracy'))} |")
        lines.append(f"| Priority accuracy (±1) | {_pct(metrics.get('priority_accuracy_pm1'))} |")
        lines.append(f"| Priority accuracy (exact) | {_pct(metrics.get('priority_accuracy_exact'))} |")
        lines.append(f"| Disposition accuracy | {_pct(metrics.get('disposition_accuracy'))} |")
        tools = metrics.get("tools") or {}
        lines.append(f"| Tool precision | {_pct(tools.get('precision'))} |")
        lines.append(f"| Tool recall | {_pct(tools.get('recall'))} |")
        lines.append(f"| **Unsafe action rate** | {_pct(metrics.get('unsafe_action_rate'))} |")
        lines.append(f"| Unnecessary escalation | {_pct(metrics.get('unnecessary_escalation_rate'))} |")
        lines.append(f"| Overconfidence (claimed resolved) | {_pct(metrics.get('overconfidence_rate'))} |")
        latency = metrics.get("latency") or {}
        lines.append(f"| Latency p50 | {_fmt(latency.get('p50_ms'))} ms |")
        lines.append(f"| Latency p95 | {_fmt(latency.get('p95_ms'))} ms |")
        cost = metrics.get("cost") or {}
        lines.append(f"| Cost per case (mean) | ${_fmt(cost.get('mean_usd'))} |")
        lines.append(f"| Priced cases | {cost.get('priced_cases', 0)} / {run.case_count} |")
        lines.append("")
        if not cost.get("priced_cases"):
            lines.append(
                "> Cost metrics are unavailable because this model has no `ModelPrice` row.\n"
                "> They are reported as `—` rather than `0.00`, which would be a false claim."
            )
            lines.append("")

        lines.append("## Gates")
        lines.append("")
        lines.append("| Gate | Result |")
        lines.append("|---|---|")
        for gate, passed in (metrics.get("gates") or {}).items():
            lines.append(f"| {gate} | {'PASS' if passed else '**FAIL**'} |")
        lines.append("")

        if by_kind:
            lines.append("## By case kind")
            lines.append("")
            lines.append("| Kind | Cases | Disposition match | Unsafe attempts |")
            lines.append("|---|---|---|---|")
            for kind in sorted(by_kind):
                rows = by_kind[kind]
                matched = sum(1 for r in rows if r.disposition_match)
                unsafe = sum(1 for r in rows if r.attempted_forbidden)
                lines.append(f"| {kind} | {len(rows)} | {matched}/{len(rows)} | {unsafe} |")
            lines.append("")

        failures = metrics.get("failures") or {}
        if failures.get("disposition_misses"):
            lines.append("## Disposition misses")
            lines.append("")
            lines.append("| Expected → actual | Cases |")
            lines.append("|---|---|")
            for transition, count in failures["disposition_misses"].items():
                lines.append(f"| `{transition}` | {count} |")
            lines.append("")

        unsafe_rows = [r for r in results if r.attempted_forbidden]
        if unsafe_rows:
            lines.append("## Unsafe attempts")
            lines.append("")
            lines.append("| Case | Attempted |")
            lines.append("|---|---|")
            for row in unsafe_rows[:25]:
                lines.append(f"| `{row.case_id}` | {', '.join(row.attempted_forbidden)} |")
            lines.append("")

        lines.append("## How to reproduce")
        lines.append("")
        lines.append("```bash")
        lines.append("cd backend")
        lines.append(f"../.venv/Scripts/python manage.py run_evals --mode {run.mode}")
        lines.append("../.venv/Scripts/python manage.py eval_report")
        lines.append("```")
        lines.append("")
        lines.append(
            "Every figure above comes from the committed dataset at "
            "`evals/dataset/cases.jsonl`."
        )
        lines.append("")

        output = Path(options["output"])
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text("\n".join(lines), encoding="utf-8")
        self.stdout.write(self.style.SUCCESS(f"wrote {output}"))
